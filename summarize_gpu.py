#!/usr/bin/env python3
"""Summarize GPU sidecar logs (run_config.sh, LAB_LOG section 25) for the clean rerun. CPU only.

For every results/clean/**/gpu_*.csv: samples, median and min SM clock, median power, max temperature, distinct
clocks_event_reasons.active values with their share of samples, and samples with decoder/encoder > 0 (other GPU users).
"busy" = samples with utilization.gpu >= BUSY_UTIL (the benchmark phases; excludes startup, idle gaps and shutdown).
Flags a run whose busy median SM clock differs from the median of its sibling reps by more than CLOCK_TOL, or whose set
of event-reason values differs from its siblings'. Printed numbers are truncated, never rounded up.
Writes results/clean/gpu_summary.md (timestamped name if it exists) and prints the same text.
"""
import csv, glob, math, os, re, statistics, sys, time
from collections import Counter, defaultdict

BUSY_UTIL = 50
CLOCK_TOL = 0.02
# nvml.h nvmlClocksEventReason* bits. 0x400: nvidia-smi -q showed only "Reliability" Active while it was set (LAB_LOG 25).
BITS = {0x1: "GpuIdle", 0x2: "AppClocks", 0x4: "SwPowerCap", 0x8: "HwSlowdown", 0x10: "SyncBoost",
        0x20: "SwThermal", 0x40: "HwThermal", 0x80: "HwPowerBrake", 0x100: "DisplayClock", 0x400: "Reliability(?)"}


def trunc(x, d=0):
    f = 10 ** d
    return f"{math.trunc(x * f) / f:.{d}f}"


def num(s):
    m = re.match(r"\s*([-0-9.]+)", s)
    return float(m.group(1)) if m else None


def decode(v):
    try:
        b = int(v, 16)
    except ValueError:
        return v
    names = [n for bit, n in BITS.items() if b & bit]
    rest = b & ~sum(BITS)
    if rest:
        names.append(f"unknown 0x{rest:x}")
    return "+".join(names) if names else "none"


def load(path):
    rows = []
    with open(path) as f:
        r = csv.reader(f)
        next(r, None)
        for row in r:
            if len(row) < 10:
                continue
            util, dec, enc, mem, sm, memclk, pw, temp = (num(x) for x in row[1:9])
            if None in (util, sm, pw, temp):
                continue
            rows.append(dict(ts=row[0].strip(), util=util, dec=dec or 0, enc=enc or 0, mem=mem, sm=sm, memclk=memclk,
                             pw=pw, temp=temp, why=row[9].strip()))
    return rows


def main():
    files = sorted(glob.glob("results/clean/gpu_*.csv") + glob.glob("results/clean/**/gpu_*.csv", recursive=True))
    files = sorted(set(files))
    runs = {}
    for f in files:
        name = re.sub(r"^gpu_|\.csv$", "", os.path.basename(f))
        rows = load(f)
        if not rows:
            continue
        busy = [r for r in rows if r["util"] >= BUSY_UTIL]
        reasons = Counter(r["why"] for r in rows)
        runs[name] = dict(file=f, rows=rows, busy=busy, reasons=reasons,
                          first=rows[0]["ts"], last=rows[-1]["ts"])
    # sibling groups: name without -repN
    groups = defaultdict(list)
    for n in runs:
        groups[re.sub(r"-rep\d+$", "", n)].append(n)
    out = []
    p = out.append
    p("# GPU sidecar summary, clean rerun (2026-10-10)")
    p("")
    p(f"Generated by summarize_gpu.py from results/clean/**/gpu_*.csv (1 Hz nvidia-smi, LAB_LOG section 25). busy = samples with")
    p(f"utilization.gpu >= {BUSY_UTIL}%. FLAG = busy median SM clock differs from the median of its sibling reps by > "
      f"{int(CLOCK_TOL * 100)}%, or its set of event-reason values differs from a sibling's. Truncated, never rounded up.")
    p("")
    p("| run | samples | busy | SM MHz median / min (all) | SM MHz median / min (busy) | mem MHz values | power W median (all / busy) | max temp C | dec/enc > 0 samples | event reasons (share of samples) | flag |")
    p("|---|---|---|---|---|---|---|---|---|---|---|")
    for g in sorted(groups):
        names = sorted(groups[g])
        busy_meds = {n: statistics.median([r["sm"] for r in runs[n]["busy"]]) for n in names if runs[n]["busy"]}
        for n in names:
            R = runs[n]
            rows, busy = R["rows"], R["busy"]
            flags = []
            sib = [busy_meds[m] for m in names if m != n and m in busy_meds]
            if n in busy_meds and sib:
                ref = statistics.median(sib)
                if abs(busy_meds[n] / ref - 1) > CLOCK_TOL:
                    flags.append(f"busy SM {trunc(busy_meds[n])} vs siblings {trunc(ref)}")
            for m in names:
                if m != n and set(runs[m]["reasons"]) != set(R["reasons"]):
                    flags.append(f"reasons differ from {m}")
                    break
            sm_all = [r["sm"] for r in rows]
            sm_busy = [r["sm"] for r in busy]
            memclks = sorted({int(r["memclk"]) for r in rows if r["memclk"] is not None})
            de = sum(1 for r in rows if r["dec"] > 0 or r["enc"] > 0)
            reasons = ", ".join(f"{v} {decode(v)} {trunc(100 * c / len(rows), 1)}%"
                                for v, c in R["reasons"].most_common())
            pw_busy = trunc(statistics.median([r["pw"] for r in busy]), 1) if busy else "n/a"
            p(f"| {n} | {len(rows)} | {len(busy)} | {trunc(statistics.median(sm_all))} / {trunc(min(sm_all))} | "
              + (f"{trunc(statistics.median(sm_busy))} / {trunc(min(sm_busy))}" if busy else "n/a")
              + f" | {', '.join(map(str, memclks))} | {trunc(statistics.median([r['pw'] for r in rows]), 1)} / {pw_busy} | "
              f"{trunc(max(r['temp'] for r in rows))} | {de} | {reasons} | {'; '.join(flags) or '-'} |")
    text = "\n".join(out) + "\n"
    if "--no-write" in sys.argv:
        sys.stdout.write(text)
        return
    dst = "results/clean/gpu_summary.md"
    if os.path.exists(dst):
        dst = f"results/clean/gpu_summary_{time.strftime('%Y%m%d_%H%M%S')}.md"
    with open(dst, "w") as f:
        f.write(text)
    sys.stdout.write(text)
    print(f"\n(wrote {dst})")


if __name__ == "__main__":
    main()
